            var actualCueIn = Assert.Single(signals, s => s.Kind == ExplicitMarkerKind.CueIn);
            Assert.Equal(DateTimeOffset.UnixEpoch + TimeSpan.FromSeconds(2.0), actualCueIn.ObservedAt);
        }
        finally
        {
            File.Delete(filePath);
        }
    }

