                WriteSection(writer, pmtPid, BuildPmtSection(scte35Pid));

                var cueOut = BuildSpliceInsertSection(eventId: 1, cueOut: true, ptsTime: 90_000);
                var cueIn = BuildSpliceInsertSection(eventId: 2, cueOut: false, ptsTime: 180_000);
